/*                                  LOOKUP                                    */
/* -------------------------------------------------------------------------- */

// Build a case-insensitive lookup map
const ACRO_LOOKUP = new Map();
for (const [k, v] of Object.entries(ACRONYMS)) {
  ACRO_LOOKUP.set(k.toLowerCase(), v);
}

// Ambiguous acronyms — if name_en suggests an alternate meaning, override.
// Keys = short lowercase. Values = { matcher: regex applied to name_en, explanation }.
const DISAMBIGUATE = {
  ltv: [
    {
      matcher: /loan[\s-]?to[\s-]?value/i,
      explanation: "Loan-to-Value ratio — debt divided by the value of the underlying assets.",
    },
    // default Lifetime Value handled by main dict
  ],
  bv: [
    {
      matcher: /brand\s+value/i,
      explanation: 'Brand Value — estimated monetary value of the brand.',
    },
  ],
  cor: [
    {
      matcher: /cost\s+of\s+revenue/i,
      explanation: "Cost of Revenue — direct cost attributable to producing the revenue.",
    },
  ],
};

function dictLookup(short, nameEn) {
  if (!short || typeof short !== 'string') return null;
  const key = short.trim().toLowerCase();

  // Disambiguation first
  const alts = DISAMBIGUATE[key];
  if (alts && nameEn && typeof nameEn === 'string') {
    for (const alt of alts) {
      if (alt.matcher.test(nameEn)) {
        return alt.explanation;
      }
    }
  }

  return ACRO_LOOKUP.get(key) || null;
}

/* -------------------------------------------------------------------------- */
/*                                 FILE WALK                                  */
/* -------------------------------------------------------------------------- */

function isMainPipelineFile(filename) {
  if (filename.startsWith('_')) return false;
  for (const tag of SKIP_TAGS) {
    if (filename.includes(tag)) return false;
  }
  return filename.endsWith('.json');
}

function listFiles() {
  const all = [];
  for (const dir of DIRS) {
    if (!fs.existsSync(dir)) continue;
    const names = fs.readdirSync(dir);
    for (const n of names) {
      if (!isMainPipelineFile(n)) continue;
      all.push(path.join(dir, n));
    }
  }
  return all;
}

/* -------------------------------------------------------------------------- */
/*                                   MAIN                                     */
/* -------------------------------------------------------------------------- */

function main() {
  const files = listFiles();
  console.log(`Scanning ${files.length} pipeline files...`);

  let totalKpis = 0;
  let alreadyHasEn = 0;
  let filledByDict = 0;
  let filledByTemplate = 0;
  let skipped = 0;
  let filesChanged = 0;

  const samples = [];

  for (const f of files) {
    let data;
    try {
      data = JSON.parse(fs.readFileSync(f, 'utf8'));
    } catch (e) {
      continue;
    }
    if (!data || !Array.isArray(data.kpis)) continue;

    let changed = false;
    for (const k of data.kpis) {
      totalKpis += 1;
      if (k.explanation_en && String(k.explanation_en).trim().length > 0) {
        alreadyHasEn += 1;
        continue;
      }
      const short = k.short;
      if (!short || typeof short !== 'string') {
        skipped += 1;
        continue;
      }

      // 1. Dict acronym
      const dictHit = dictLookup(short, k.name_en);
      if (dictHit) {
        k.explanation_en = dictHit;
        filledByDict += 1;
        changed = true;
        if (samples.length < 10) samples.push({ file: path.basename(f), short, source: 'dict', explanation_en: dictHit });
        continue;
      }

      // 2. Pattern template
      const tplHit = templateMatch(short);
      if (tplHit) {
        k.explanation_en = tplHit;
        filledByTemplate += 1;
        changed = true;
        if (samples.length < 10) samples.push({ file: path.basename(f), short, source: 'template', explanation_en: tplHit });
        continue;
      }

      // 3. Skip
      skipped += 1;
    }

    if (changed) {
      fs.writeFileSync(f, JSON.stringify(data, null, 2) + '\n', 'utf8');
      filesChanged += 1;
    }
  }

  const beforeEn = alreadyHasEn;
  const afterEn = alreadyHasEn + filledByDict + filledByTemplate;

  console.log('\n=== Heuristic explanation_en — Stats ===');
  console.log(`Total KPIs scanned       : ${totalKpis}`);
  console.log(`Already had explanation_en: ${alreadyHasEn} (${pct(alreadyHasEn, totalKpis)}%)`);
  console.log(`Filled via dict (acronyms): ${filledByDict}`);
  console.log(`Filled via template      : ${filledByTemplate}`);
  console.log(`Skipped (no match)       : ${skipped}`);
  console.log(`Files changed            : ${filesChanged}`);
  console.log('');
  console.log(`Coverage before : ${beforeEn}/${totalKpis} (${pct(beforeEn, totalKpis)}%)`);
  console.log(`Coverage after  : ${afterEn}/${totalKpis} (${pct(afterEn, totalKpis)}%)`);
  console.log(`Delta           : +${afterEn - beforeEn} KPIs (+${pct(afterEn - beforeEn, totalKpis)} pts)`);
  console.log('');
  console.log('=== Sample 10 KPIs filled ===');
  for (const s of samples) {
    console.log(`- [${s.source}] ${s.file} :: "${s.short}" → ${s.explanation_en}`);
  }
}

function pct(n, d) {
  if (!d) return '0.00';
  return ((100 * n) / d).toFixed(2);
}

main();
