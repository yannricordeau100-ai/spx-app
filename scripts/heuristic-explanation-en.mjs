// Returns an explanation_en string or null if no pattern matches.
function templateMatch(short) {
  if (!short || typeof short !== 'string') return null;
  const s = short.trim();
  if (!s) return null;

  // Word characters incl. & and dashes for segment names.
  // We avoid being too greedy: pattern must end with the trigger keyword.

  // "X CAGR" → 5-year CAGR (very common)
  let m = s.match(/^(.+?)\s+CAGR$/i);
  if (m) {
    const x = m[1].trim();
    return `Compound annual growth rate of ${x} over the period.`;
  }

  // "X Growth" → YoY growth in X
  m = s.match(/^(.+?)\s+Growth$/i);
  if (m) {
    const x = m[1].trim();
    return `Year-over-year growth in ${x}.`;
  }

  // "X Margin" → profit margin on X
  m = s.match(/^(.+?)\s+Margin$/i);
  if (m) {
    const x = m[1].trim();
    return `Profit margin on ${x}.`;
  }

  // "Revenue X" → Revenue from X segment (only when X is plausible segment name,
  //   ie. starts with uppercase letter, not too long)
  m = s.match(/^Revenue\s+(.+)$/i);
  if (m) {
    const x = m[1].trim();
    if (x.length > 0 && x.length < 60) {
      return `Revenue from the ${x} segment.`;
    }
  }

  // "X Revenue" → Revenue from segment X
  m = s.match(/^(.+?)\s+Revenue$/i);
  if (m) {
    const x = m[1].trim();
    if (x.length > 0 && x.length < 60) {
      return `Revenue from the ${x} segment.`;
    }
  }

  // "X Sales"
  m = s.match(/^(.+?)\s+Sales$/i);
  if (m) {
    const x = m[1].trim();
    if (x.length > 0 && x.length < 60) {
      return `Sales generated by the ${x} segment.`;
    }
  }

  // "X Volume"
  m = s.match(/^(.+?)\s+Volume$/i);
  if (m) {
    const x = m[1].trim();
    return `Volume of ${x} over the period.`;
  }

  // "X Production"
  m = s.match(/^(.+?)\s+Production$/i);
  if (m) {
    const x = m[1].trim();
    return `Production of ${x} over the period.`;
  }

  // "X Yield"
  m = s.match(/^(.+?)\s+Yield$/i);
  if (m) {
    const x = m[1].trim();
    return `Yield on ${x}.`;
  }

  // "X Ratio"
  m = s.match(/^(.+?)\s+Ratio$/i);
  if (m) {
    const x = m[1].trim();
    return `${x} ratio.`;
  }

  // "X Income"
  m = s.match(/^(.+?)\s+Income$/i);
  if (m) {
    const x = m[1].trim();
    if (x.length > 0 && x.length < 40) {
      return `${x} income generated over the period.`;
    }
  }

  // "X Investment"
  m = s.match(/^(.+?)\s+Investment$/i);
  if (m) {
    const x = m[1].trim();
    return `Investment in ${x}.`;
  }

  // "X Costs" / "X Cost"
  m = s.match(/^(.+?)\s+Costs?$/i);
  if (m) {
    const x = m[1].trim();
    return `Costs related to ${x}.`;
  }

  // "X Expenses"
  m = s.match(/^(.+?)\s+Expenses$/i);
  if (m) {
    const x = m[1].trim();
    return `Expenses related to ${x}.`;
  }

  // "X Users"
  m = s.match(/^(.+?)\s+Users$/i);
  if (m) {
    const x = m[1].trim();
    return `Number of ${x} users.`;
  }

  // "X Customers" / "X Subscribers"
  m = s.match(/^(.+?)\s+(Customers|Subscribers|Members)$/i);
  if (m) {
    const x = m[1].trim();
    const noun = m[2].toLowerCase();
    return `Number of ${x} ${noun}.`;
  }

  // "X Concentration"
  m = s.match(/^(.+?)\s+Concentration$/i);
  if (m) {
    const x = m[1].trim();
    return `${x} concentration — share of total attributed to the largest contributors.`;
  }

  // "X Share" (market share)
  m = s.match(/^(.+?)\s+Share$/i);
  if (m) {
    const x = m[1].trim();
    return `Market share in ${x}.`;
  }

  return null;
}

